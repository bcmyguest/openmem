#!/usr/bin/env node
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

// compose.override.yaml belongs to the mutable stack root (PM_STACK_ROOT), not the code root.
const repo = path.resolve(
  process.env.PM_STACK_ROOT || path.join(path.dirname(fileURLToPath(import.meta.url)), ".."),
);
const home = process.env.HOME || os.homedir();
const out = path.join(repo, "compose.override.yaml");

const dirs = [
  ".ssh",
  ".gnupg",
  ".config/hindsight",
  // Provider env files with API keys (mem0.env, ...). The indexer never reads it.
  ".config/personal-memory",
  ".config/notebooklm",
  ".notebooklm",
  ".aws",
  ".config/gcloud",
  ".config/gh",
  ".config/glab-cli",
  ".kube",
  ".docker",
  ".mozilla",
  ".config/google-chrome",
  ".config/chromium",
  ".password-store",
  ".local/share/keyrings",
  ".config/fnox",
  ".local/share/fnox",
  ".secrets",
];
const files = [
  ".codex/auth.json",
  ".claude/.credentials.json",
  ".claude.json",
  ".netrc",
  ".git-credentials",
  ".npmrc",
  ".pypirc",
];

const tmpfsLines = [];
for (const d of dirs) {
  if (fs.existsSync(path.join(home, d)) && fs.statSync(path.join(home, d)).isDirectory()) {
    tmpfsLines.push(`      - "${path.join(home, d)}"`);
  }
}
const volumeLines = [];
for (const f of files) {
  if (fs.existsSync(path.join(home, f)) && fs.statSync(path.join(home, f)).isFile()) {
    volumeLines.push(`      - "/dev/null:${path.join(home, f)}:ro"`);
  }
}
const userIndex = path.join(home, ".config/hindsight/index.yml");
const envLines = [];
if (fs.existsSync(userIndex)) {
  volumeLines.push(`      - "${userIndex}:/etc/hindsight/index.yml:ro"`);
  envLines.push("      HINDSIGHT_INDEX_CONFIG: /etc/hindsight/index.yml");
}

const parts = [
  "# Generated by scripts/gen-masks.mjs for this host. Do not commit.",
  "services:",
  "  indexer:",
];
if (tmpfsLines.length) {
  parts.push("    tmpfs:", ...tmpfsLines);
}
if (volumeLines.length) {
  parts.push("    volumes:", ...volumeLines);
}
if (envLines.length) {
  parts.push("    environment:", ...envLines);
}
parts.push("");

fs.writeFileSync(out, parts.join("\n"));
console.log(`wrote ${out}`);
