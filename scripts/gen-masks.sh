#!/usr/bin/env bash
# Writes compose.override.yaml (git-ignored). It hides secret paths under $HOME from the indexer container.
# Only paths that exist get a mask: Docker creates a missing mount target inside the $HOME bind mount,
# which leaves a root-owned directory or file on the host.
# Re-run after a secret directory is created later; the mask list is fixed at generation time.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${repo}/compose.override.yaml"
dirs=(.ssh .gnupg .config/hindsight .aws .config/gcloud .kube .docker .mozilla .config/google-chrome .config/chromium .password-store .local/share/keyrings)
files=(.codex/auth.json .claude/.credentials.json)

tmpfs_lines=()
for d in "${dirs[@]}"; do
    [ -d "${HOME}/${d}" ] && tmpfs_lines+=("      - \"${HOME}/${d}\"")
done
volume_lines=()
for f in "${files[@]}"; do
    [ -f "${HOME}/${f}" ] && volume_lines+=("      - \"/dev/null:${HOME}/${f}:ro\"")
done
# ~/.config/hindsight is masked by a root-owned tmpfs, so the indexer cannot read a per-machine index.yml there.
# When it exists, bind-mount it to /etc/hindsight/index.yml and point HINDSIGHT_INDEX_CONFIG at it. It holds no secrets.
user_index="${HOME}/.config/hindsight/index.yml"
env_lines=()
if [ -f "${user_index}" ]; then
    volume_lines+=("      - \"${user_index}:/etc/hindsight/index.yml:ro\"")
    env_lines+=("      HINDSIGHT_INDEX_CONFIG: /etc/hindsight/index.yml")
fi

{
    echo "# Generated by scripts/gen-masks.sh for this host. Do not commit."
    echo "services:"
    echo "  indexer:"
    if [ "${#tmpfs_lines[@]}" -gt 0 ]; then
        echo "    tmpfs:"
        printf '%s\n' "${tmpfs_lines[@]}"
    fi
    if [ "${#volume_lines[@]}" -gt 0 ]; then
        echo "    volumes:"
        printf '%s\n' "${volume_lines[@]}"
    fi
    if [ "${#env_lines[@]}" -gt 0 ]; then
        echo "    environment:"
        printf '%s\n' "${env_lines[@]}"
    fi
} > "${out}"

echo "wrote ${out}: ${#tmpfs_lines[@]} directory mask(s), ${#volume_lines[@]} file mount(s), per-machine index.yml: $([ "${#env_lines[@]}" -gt 0 ] && echo yes || echo no)"
