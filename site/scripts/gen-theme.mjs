// Generates src/styles/tokens.css from src/theme.yml and checks WCAG AA
// contrast for the text/background pairs the site uses. Exits 1 on a failing
// pair, so a palette edit cannot ship unreadable text.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = new URL('..', import.meta.url);
const { light, dark } = parse(readFileSync(new URL('src/theme.yml', root), 'utf8')).theme.semantic;

const channel = (v) => {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = (hex) => {
  const n = Number.parseInt(hex.slice(1), 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
};
export const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const PAIRS = [
  ['ink', 'canvas'],
  ['ink', 'panel'],
  ['muted', 'canvas'],
  ['muted', 'panel'],
  ['muted', 'panel-raised'],
  ['muted', 'code'],
  ['brand', 'canvas'],
  ['brand', 'panel'],
  ['source', 'panel'],
  ['source', 'brand-soft'],
  ['warning', 'panel'],
];
const failures = [];
for (const [name, tokens] of [['light', light], ['dark', dark]]) {
  for (const [fg, bg] of PAIRS) {
    const ratio = contrast(tokens[fg], tokens[bg]);
    if (ratio < 4.5) failures.push(`${name}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1 (needs 4.5:1)`);
  }
}
if (failures.length) {
  console.error(`gen-theme: contrast failures\n  ${failures.join('\n  ')}`);
  process.exit(1);
}

const vars = (tokens) =>
  Object.entries(tokens)
    .map(([name, value]) => `  --c-${name}: ${value};`)
    .join('\n');

// Starlight palette on the same tokens. Starlight's unattributed root is dark.
const starlight = (t) =>
  [
    `  --sl-color-accent-low: ${t['brand-soft']};`,
    `  --sl-color-accent: ${t.brand};`,
    `  --sl-color-accent-high: ${t.source};`,
    `  --sl-color-white: ${t.ink};`,
    `  --sl-color-gray-1: ${t.ink};`,
    `  --sl-color-gray-2: ${t.muted};`,
    `  --sl-color-gray-3: ${t.muted};`,
    `  --sl-color-gray-4: ${t.line};`,
    `  --sl-color-gray-5: ${t.line};`,
    `  --sl-color-gray-6: ${t['panel-raised']};`,
    `  --sl-color-gray-7: ${t.panel};`,
    `  --sl-color-black: ${t.canvas};`,
    `  --sl-color-bg-nav: ${t.panel};`,
    `  --sl-color-bg-sidebar: ${t.panel};`,
    `  --sl-color-hairline: ${t.line};`,
    `  --sl-color-hairline-light: ${t.line};`,
    `  --sl-color-hairline-shade: ${t.line};`,
  ].join('\n');

const css = `/* Generated by scripts/gen-theme.mjs from src/theme.yml. Do not edit. */
:root,
:root[data-theme='dark'] {
${vars(dark)}
  color-scheme: dark;
}
:root[data-theme='light'] {
${vars(light)}
  color-scheme: light;
}
/* Starlight palette */
:root,
:root[data-theme='dark'] {
${starlight(dark)}
}
:root[data-theme='light'] {
${starlight(light)}
}
`;

writeFileSync(fileURLToPath(new URL('src/styles/tokens.css', root)), css);
console.log('gen-theme: wrote src/styles/tokens.css (contrast checks passed)');
