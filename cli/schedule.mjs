#!/usr/bin/env node
/** Install a per-user, hourly feed-sync job using the host scheduler. */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";
import { pythonCandidates } from "./feed-sync.mjs";
import { isMainModule } from "./is-main.mjs";

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PACKAGE_NAME = JSON.parse(fs.readFileSync(path.join(PACKAGE_ROOT, "package.json"), "utf8")).name;
const JOB_NAME = "openmem-feed-sync";
const LAUNCHD_LABEL = "io.github.bcmyguest.openmem.feed-sync";
const WINDOWS_TASK = "OpenMemFeedSync";

function escapeXml(value) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}

function systemdArg(value) {
  const escaped = value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("%", "%%");
  return `"${escaped}"`;
}

export function schedulePaths(platform, home, env = process.env) {
  if (platform === "linux") {
    const config = path.isAbsolute(env.XDG_CONFIG_HOME || "") ? env.XDG_CONFIG_HOME : path.join(home, ".config");
    return {
      runner: path.join(config, "openmem", "feed-sync-runner.mjs"),
      service: path.join(config, "systemd", "user", `${JOB_NAME}.service`),
      timer: path.join(config, "systemd", "user", `${JOB_NAME}.timer`),
    };
  }
  if (platform === "darwin") {
    return {
      runner: path.join(home, "Library", "Application Support", "OpenMem", "feed-sync-runner.mjs"),
      plist: path.join(home, "Library", "LaunchAgents", `${LAUNCHD_LABEL}.plist`),
    };
  }
  if (platform === "win32") {
    const local = path.win32.isAbsolute(env.LOCALAPPDATA || "") ? env.LOCALAPPDATA : path.win32.join(home, "AppData", "Local");
    return { runner: path.win32.join(local, "OpenMem", "feed-sync-runner.mjs") };
  }
  throw new Error(`native scheduling is unavailable on ${platform}; run ${PACKAGE_NAME} feed-sync with your system scheduler`);
}

export function renderRunner(nodePath, npmCliPath, pythonPath) {
  return `// Generated by OpenMem schedule install. Reinstall after changing Node.js installations.\n` +
    `import { spawnSync } from "node:child_process";\n` +
    `import path from "node:path";\n` +
    `const node = ${JSON.stringify(nodePath)};\n` +
    `const npm = ${JSON.stringify(npmCliPath)};\n` +
    `const python = ${JSON.stringify(pythonPath)};\n` +
    `const env = { ...process.env };\n` +
    `const pathKey = Object.keys(env).find((key) => key.toLowerCase() === "path") || "PATH";\n` +
    `env[pathKey] = [path.dirname(node), path.dirname(python), env[pathKey] || ""].join(path.delimiter);\n` +
    `env.PYTHON = python;\n` +
    `const result = spawnSync(node, [npm, "exec", "--yes", "--package=${PACKAGE_NAME}", "--", "openmem", "feed-sync"], { env, stdio: "inherit" });\n` +
    `if (result.error) console.error(result.error.message);\n` +
    `process.exit(result.status ?? 1);\n`;
}

export function renderSystemdUnits(nodePath, runnerPath) {
  return {
    service: `[Unit]\nDescription=Refresh OpenMem feed cache\n\n[Service]\nType=oneshot\nExecStart=${systemdArg(nodePath)} ${systemdArg(runnerPath)}\n`,
    timer: `[Unit]\nDescription=Refresh OpenMem feed cache hourly\n\n[Timer]\nOnCalendar=hourly\nPersistent=true\n\n[Install]\nWantedBy=timers.target\n`,
  };
}

export function renderLaunchAgent(nodePath, runnerPath) {
  return `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n` +
    `<plist version="1.0"><dict>\n` +
    `  <key>Label</key><string>${LAUNCHD_LABEL}</string>\n` +
    `  <key>ProgramArguments</key><array><string>${escapeXml(nodePath)}</string><string>${escapeXml(runnerPath)}</string></array>\n` +
    `  <key>StartInterval</key><integer>3600</integer>\n` +
    `</dict></plist>\n`;
}

export function windowsTaskArgs(nodePath, runnerPath) {
  return ["/create", "/sc", "hourly", "/mo", "1", "/tn", WINDOWS_TASK, "/tr", `"${nodePath}" "${runnerPath}"`, "/f"];
}

function run(command, args, env, allowMissing = false) {
  const result = spawnSync(command, args, { encoding: "utf8", env });
  if (result.error) throw result.error;
  if (result.status !== 0 && !allowMissing) throw new Error(`${command} ${args.join(" ")}: ${(result.stderr || result.stdout).trim()}`);
  return result.status === 0;
}

function writeFile(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, { mode: 0o600 });
}

function resolvePython(platform, env) {
  for (const [command, prefix] of pythonCandidates(platform, env)) {
    const result = spawnSync(command, [...prefix, "-c", "import sys, yaml; print(sys.executable)"], { encoding: "utf8", env });
    if (result.status === 0) return result.stdout.trim();
  }
  throw new Error("Python 3 with PyYAML is required for feed sync; install PyYAML or set PYTHON to a working interpreter");
}

function install(platform, home, env, dryRun) {
  const files = schedulePaths(platform, home, env);
  const npmCli = env.npm_execpath;
  if (!npmCli || !fs.existsSync(npmCli)) throw new Error("run schedule install through npx so OpenMem can locate npm");
  const nodePath = process.execPath;
  if (dryRun) {
    console.log(`Would write ${files.runner} and install an hourly ${JOB_NAME} job using ${nodePath} and ${npmCli}`);
    return;
  }
  const runner = renderRunner(nodePath, npmCli, resolvePython(platform, env));
  writeFile(files.runner, runner);
  if (platform === "linux") {
    const units = renderSystemdUnits(nodePath, files.runner);
    writeFile(files.service, units.service);
    writeFile(files.timer, units.timer);
    run("systemctl", ["--user", "daemon-reload"], env);
    run("systemctl", ["--user", "enable", "--now", `${JOB_NAME}.timer`], env);
  } else if (platform === "darwin") {
    const target = `gui/${process.getuid()}`;
    if (fs.existsSync(files.plist)) run("launchctl", ["bootout", target, files.plist], env, true);
    writeFile(files.plist, renderLaunchAgent(nodePath, files.runner));
    run("launchctl", ["bootstrap", target, files.plist], env);
  } else {
    run("schtasks", windowsTaskArgs(nodePath, files.runner), env);
  }
  console.log(`Installed hourly ${JOB_NAME} job`);
}

function remove(platform, home, env, dryRun) {
  const files = schedulePaths(platform, home, env);
  if (dryRun) {
    console.log(`Would remove ${JOB_NAME} job and ${files.runner}`);
    return;
  }
  if (platform === "linux") {
    run("systemctl", ["--user", "disable", "--now", `${JOB_NAME}.timer`], env, true);
    fs.rmSync(files.service, { force: true });
    fs.rmSync(files.timer, { force: true });
    run("systemctl", ["--user", "daemon-reload"], env);
  } else if (platform === "darwin") {
    if (fs.existsSync(files.plist)) run("launchctl", ["bootout", `gui/${process.getuid()}`, files.plist], env, true);
    fs.rmSync(files.plist, { force: true });
  } else {
    if (run("schtasks", ["/query", "/tn", WINDOWS_TASK], env, true)) {
      run("schtasks", ["/delete", "/tn", WINDOWS_TASK, "/f"], env);
    }
  }
  fs.rmSync(files.runner, { force: true });
  console.log(`Removed ${JOB_NAME} job`);
}

export function main(argv = process.argv.slice(2), platform = process.platform, home = os.homedir(), env = process.env) {
  const { values, positionals } = parseArgs({ args: argv, options: { "dry-run": { type: "boolean" }, help: { type: "boolean" } }, allowPositionals: true });
  if (values.help || positionals.length === 0) {
    console.log(`Usage: npx ${PACKAGE_NAME} schedule <install|remove> [--dry-run]\nInstalls an hourly per-user feed sync with the native OS scheduler.`);
    return;
  }
  if (positionals.length !== 1) throw new Error("schedule accepts one action: install or remove");
  if (positionals[0] === "install") install(platform, home, env, values["dry-run"]);
  else if (positionals[0] === "remove") remove(platform, home, env, values["dry-run"]);
  else throw new Error(`unknown schedule action: ${positionals[0]}`);
}

if (isMainModule(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(`openmem schedule: ${error.message}`);
    process.exitCode = 1;
  }
}
